from lxml import etree

from odoo.tests import tagged
from odoo.tests.common import TransactionCase
from odoo.tools.safe_eval import safe_eval


@tagged("post_install", "-at_install", "l10n_ve_accountant_partner_domain")
class TestPartnerIdDomain(TransactionCase):

    def test_form_view_partner_id_has_no_domain(self):
        """The invoice form partner_id node must not declare a view domain.

        An explicit domain on the view node replaces (does not extend) the
        check_company domain generated by the ORM for the field, which hides
        matrix-company and shared contacts on branch invoices.
        """
        view = self.env["account.move"].get_view(view_type="form")
        arch = etree.fromstring(view["arch"])
        nodes = arch.xpath("//field[@name='partner_id']")
        self.assertTrue(
            nodes,
            "Expected at least one partner_id field in the invoice form view",
        )
        # locate_node (template_inheritance.py) applies an xpath position
        # replace only to the first match; that is the main form field.
        field_node = nodes[0]
        self.assertIsNone(
            field_node.get("domain"),
            "partner_id in the invoice form must not declare a domain "
            "attribute; it would override the check_company domain and hide "
            "matrix/shared contacts on branch invoices",
        )
        # Guard the minimal change: the other attributes must remain intact.
        self.assertIsNotNone(
            field_node.get("context"),
            "partner_id must keep its context attribute",
        )
        self.assertIsNotNone(
            field_node.get("options"),
            "partner_id must keep its options attribute",
        )
        self.assertIsNotNone(
            field_node.get("invisible"),
            "partner_id must keep its invisible attribute",
        )

    def _effective_partner_id_domain_str(self):
        """Return the domain string the web client uses for partner_id.

        Mirrors web/static/src/views/fields/field.js: a domain declared on the
        view node replaces the field domain; without it the client falls back
        to the one built by the ORM (check_company) and served by fields_get.
        """
        move = self.env["account.move"]
        arch = etree.fromstring(move.get_view(view_type="form")["arch"])
        # Same first-match assumption as the view-node test above.
        node = arch.xpath("//field[@name='partner_id']")[0]
        return (
            node.get("domain")
            or move.fields_get(["partner_id"])["partner_id"]["domain"]
        )

    def _evaluated_partner_id_domain(self, company):
        """Evaluate the effective domain for an invoice of ``company``.

        The domain string references the bare variable ``company_id``;
        evaluating it with safe_eval is what the web client does when the user
        opens an invoice of that company.
        """
        return safe_eval(
            self._effective_partner_id_domain_str(), {"company_id": company.id}
        )

    def _create_companies(self, prefix):
        currency = self.env.company.currency_id
        Company = self.env["res.company"]
        parent = Company.create({"name": f"{prefix} Parent", "currency_id": currency.id})
        child = Company.create(
            {
                "name": f"{prefix} Child",
                "currency_id": currency.id,
                "parent_id": parent.id,
            }
        )
        unrelated = Company.create(
            {"name": f"{prefix} Unrelated", "currency_id": currency.id}
        )
        return parent, child, unrelated

    def test_check_company_domain_matrix_valid_unrelated_invalid(self):
        """The effective partner_id domain admits matrix contacts of a branch.

        It is computed from the view node when it declares a domain, so it
        fails if a view domain such as
        [('company_id', 'in', (False, company_id))] is reintroduced: that
        domain excludes the contacts of the parent (matrix) company.
        """
        self.assertIn(
            "parent_of",
            self._effective_partner_id_domain_str(),
            "The effective partner_id domain must use parent_of so matrix "
            "contacts are selectable on branch invoices",
        )
        parent, child, unrelated = self._create_companies("TA84292")
        Partner = self.env["res.partner"]
        matrix_partner = Partner.create(
            {"name": "TA84292 Matrix Contact", "company_id": parent.id}
        )
        unrelated_partner = Partner.create(
            {"name": "TA84292 Unrelated Contact", "company_id": unrelated.id}
        )
        matched = Partner.sudo().search(self._evaluated_partner_id_domain(child))
        self.assertIn(
            matrix_partner,
            matched,
            "A contact of the matrix (parent) company must satisfy the "
            "effective domain of a child company invoice",
        )
        self.assertNotIn(
            unrelated_partner,
            matched,
            "A contact of an unrelated company must not satisfy the "
            "effective domain of a child company invoice",
        )

    def test_binaural_shared_partner_satisfies_effective_domain(self):
        """Contacts shared via company_ids satisfy the effective domain.

        Conditional on binaural_partner_multi_company: its
        _check_company_domain override adds a ('company_ids', 'parent_of', ...)
        branch. The contact belongs to an unrelated company so it can only
        match through that branch (not via company_id = False or parent_of).
        """
        if "company_ids" not in self.env["res.partner"]._fields:
            self.skipTest(
                "binaural_partner_multi_company is not installed; "
                "company_ids field not available on res.partner"
            )
        parent, child, unrelated = self._create_companies("TA84292 Joint")
        Partner = self.env["res.partner"].sudo()
        shared_partner = Partner.create(
            {
                "name": "TA84292 Shared Contact",
                "company_id": unrelated.id,
                "company_ids": [(6, 0, [parent.id])],
            }
        )
        private_partner = Partner.create(
            {"name": "TA84292 Not Shared Contact", "company_id": unrelated.id}
        )
        core_only_domain = [
            "|",
            ("company_id", "=", False),
            ("company_id", "parent_of", child.id),
        ]
        self.assertNotIn(
            shared_partner,
            Partner.search(core_only_domain),
            "Control: without the company_ids branch the shared contact "
            "must not match, so the assertion below proves that branch",
        )
        matched = Partner.search(self._evaluated_partner_id_domain(child))
        self.assertIn(
            shared_partner,
            matched,
            "A contact shared with the matrix company via company_ids must "
            "satisfy the effective domain of a child company invoice",
        )
        self.assertNotIn(
            private_partner,
            matched,
            "A contact of an unrelated company that is not shared must not "
            "satisfy the effective domain",
        )
